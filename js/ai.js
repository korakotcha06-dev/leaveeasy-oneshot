//   ถ้าใช้ static import แล้วไฟล์นั้นไม่มีอยู่ (404) เบราว์เซอร์จะโหลดทั้ง module นี้ไม่สำเร็จ
//   และเพราะหน้า new-leave-request.js import ไฟล์นี้อยู่ ทั้งหน้าจะพังไปด้วย
//   ทั้งที่ AI เป็นแค่ฟีเจอร์เสริม ไม่ใช่ฟีเจอร์หลักของการยื่นใบลา
//   การ import() แบบ dynamic ข้างในฟังก์ชัน ครอบด้วย try/catch ทำให้ไฟล์หายได้
//   โดยฟีเจอร์อื่นทั้งหมดในหน้ายังทำงานปกติ มีแค่ปุ่ม AI ที่ใช้ไม่ได้
