// เวลาสูงสุดที่ยอมรอผลจาก AI ก่อนตัดจบเอง (หน่วยมิลลิวินาที) ตามสเปกข้อ 8
const เวลาสูงสุด = 15000;

// cache ผลการโหลด config ไว้ กันไม่ต้อง import() ซ้ำทุกครั้งที่กดปุ่ม
// undefined = ยังไม่เคยลองโหลด · null = ลองแล้วไม่มีไฟล์ · object = โหลดสำเร็จ
let ค่าตั้งค่าที่โหลดแล้ว;

async function โหลดค่าตั้งค่า() {
  if (ค่าตั้งค่าที่โหลดแล้ว !== undefined) return ค่าตั้งค่าที่โหลดแล้ว;
  try {
    // เส้นทางนี้ตั้งใจเขียนเป็นสตริงตรง ๆ ไม่ผ่านตัวแปร เพื่อให้เบราว์เซอร์ resolve ได้แน่นอน
    const โมดูล = await import("./ai-config.js");
    ค่าตั้งค่าที่โหลดแล้ว = โมดูล.aiConfig || null;
  } catch (err) {
    // ไม่มีไฟล์ ai-config.js เป็นสถานการณ์ปกติของเครื่องที่ไม่ได้ตั้งค่า AI ไว้ ไม่ใช่บั๊ก
    console.warn("ai.js: ไม่พบไฟล์ js/ai-config.js ปิดฟีเจอร์ AI ให้ชั่วคราว", err);
    ค่าตั้งค่าที่โหลดแล้ว = null;
  }
  return ค่าตั้งค่าที่โหลดแล้ว;
}

// ตัดช่องว่าง/เครื่องหมายคำพูดหัวท้ายออก แล้วเทียบแบบไม่สนตัวพิมพ์เล็กใหญ่ไม่ได้เพราะเป็นภาษาไทย
// จึงเทียบตรงตัวหลังตัดช่องว่างและเครื่องหมายคำพูดพอ เพียงพอกับกรณีที่โมเดลชอบตอบ "ลาป่วย" แบบมีเครื่องหมายคำพูดล้อม
function ทำความสะอาดชื่อ(ข้อความ) {
  return String(ข้อความ || "")
    .trim()
    .replace(/^["'“”「」]+|["'“”「」]+$/g, "")
    .trim();
}

function สร้างคำสั่งให้โมเดล(เหตุผล, รายชื่อประเภท) {
  return [
    "คุณเป็นระบบช่วยจัดประเภทใบลางานของบริษัทแห่งหนึ่ง",
    `ประเภทการลาที่มีอยู่จริงในระบบตอนนี้มีเท่านี้: ${รายชื่อประเภท.join(", ")}`,
    `ข้อความเหตุผลการลาที่พนักงานพิมพ์มาคือ: "${เหตุผล}"`,
    "จากข้อความนี้ ประเภทการลาที่ตรงที่สุดคือชื่อใดในรายการข้างต้น",
    "ตอบกลับด้วยชื่อประเภทการลาตรงตัวจากรายการที่ให้มาเพียงชื่อเดียวเท่านั้น",
    "ห้ามใส่คำอธิบายอื่น ห้ามใส่เครื่องหมายคำพูด ห้ามตอบชื่อที่ไม่อยู่ในรายการ"
  ].join("\n");
}

/**
 * ขอให้ AI เดาประเภทการลาจากข้อความเหตุผล
 *
 * @param {string} เหตุผล - ข้อความในช่องเหตุผลการลาตอนนี้
 * @param {{id:string,name:string}[]} ประเภทที่มีอยู่ - ประเภทการลาที่มีอยู่จริงในระบบตอนนี้
 * @returns {Promise<{ok:true,leaveType:{id:string,name:string}} | {ok:false,message:string}>}
 *
 * คืนค่าเป็น object เสมอ ไม่โยน error ออกไปให้หน้าจอต้อง try/catch เอง
 * เพราะทุกทางที่ล้มเหลว (ไม่มี config, เน็ตหลุด, timeout, โมเดลตอบมั่ว)
 * ล้วนจบด้วยพฤติกรรมเดียวกันคือ "แจ้งเตือนแล้วปล่อยให้ผู้ใช้เลือกเอง"
 */
export async function classifyLeaveType(เหตุผล, ประเภทที่มีอยู่) {
  const ข้อความ = (เหตุผล || "").trim();
  if (!ข้อความ) {
    return { ok: false, message: "กรุณากรอกเหตุผลการลาก่อนใช้ AI ช่วยจัดประเภท" };
  }
  if (!Array.isArray(ประเภทที่มีอยู่) || ประเภทที่มีอยู่.length === 0) {
    return { ok: false, message: "ยังไม่มีประเภทการลาในระบบให้เลือก กรุณาเพิ่มประเภทก่อน" };
  }

  const ตั้งค่า = await โหลดค่าตั้งค่า();
  if (!ตั้งค่า || !ตั้งค่า.apiKey) {
    // ไม่มี config หรือไม่มี key = ปิดฟีเจอร์อย่างสุภาพ ไม่ throw ไม่ทำให้หน้าใช้งานไม่ได้
    // นี่คือสถานะที่ชุดทดสอบอัตโนมัติจะเจอเสมอ เพราะเครื่องทดสอบไม่มีไฟล์ ai-config.js
    return {
      ok: false,
      message: "ยังไม่ได้ตั้งค่า AI บนเครื่องนี้ (ไม่มีไฟล์ js/ai-config.js) กรุณาเลือกประเภทการลาเอง"
    };
  }

  // ตั้งเวลาตัดจบเอง ไม่พึ่งให้เน็ตหลุดเองหรือให้เบราว์เซอร์ค้างรอไม่รู้จบ
  // ตามสเปกข้อ 8 ที่บอกว่า timeout 15 วินาทีต้องเป็นของจริง ไม่ใช่แค่ทฤษฎี
  const ตัวควบคุมยกเลิก = new AbortController();
  const ตัวจับเวลา = setTimeout(() => ตัวควบคุมยกเลิก.abort(), เวลาสูงสุด);

  try {
    const รายชื่อประเภท = ประเภทที่มีอยู่.map((ประเภท) => ประเภท.name);

    const ผลตอบกลับ = await fetch("https://openrouter.ai/api/v1/chat/completions", {
      method: "POST",
      headers: {
        "Content-Type": "application/json",
        Authorization: `Bearer ${ตั้งค่า.apiKey}`
      },
      body: JSON.stringify({
        model: ตั้งค่า.model || "openai/gpt-4o-mini",
        temperature: 0,
        messages: [{ role: "user", content: สร้างคำสั่งให้โมเดล(ข้อความ, รายชื่อประเภท) }]
      }),
      signal: ตัวควบคุมยกเลิก.signal
    });

    if (!ผลตอบกลับ.ok) {
      return { ok: false, message: "เรียก AI ไม่สำเร็จ กรุณาเลือกประเภทการลาเอง" };
    }

    const ข้อมูล = await ผลตอบกลับ.json();
    const ข้อความที่ตอบ =
      (ข้อมูล &&
        ข้อมูล.choices &&
        ข้อมูล.choices[0] &&
        ข้อมูล.choices[0].message &&
        ข้อมูล.choices[0].message.content) ||
      "";
    const ชื่อที่ได้ = ทำความสะอาดชื่อ(ข้อความที่ตอบ);

    // กฎที่พลาดไม่ได้ตามสเปกข้อ 8: ผลต้องเป็นประเภทที่มีอยู่จริงเท่านั้น
    // เทียบหลังทำความสะอาดทั้งสองฝั่ง กันกรณีโมเดลตอบมีช่องว่างเกินมา
    const ที่ตรงกัน = ประเภทที่มีอยู่.find(
      (ประเภท) => ทำความสะอาดชื่อ(ประเภท.name) === ชื่อที่ได้
    );

    if (!ที่ตรงกัน) {
      return { ok: false, message: "AI จัดประเภทให้ไม่ได้ กรุณาเลือกประเภทการลาเอง" };
    }

    return { ok: true, leaveType: ที่ตรงกัน };
  } catch (err) {
    if (err && err.name === "AbortError") {
      return {
        ok: false,
        message: "AI ใช้เวลานานเกินไป (เกิน 15 วินาที) กรุณาเลือกประเภทการลาเอง"
      };
    }
    // ครอบคลุมทั้งเน็ตหลุดและข้อผิดพลาดที่ไม่คาดคิดอื่น ๆ ไม่ปล่อยให้หลุดขึ้นไปทำหน้าค้าง
    console.error("ai.js: classifyLeaveType ล้มเหลว", err);
    return { ok: false, message: "เรียก AI ไม่สำเร็จ กรุณาเลือกประเภทการลาเอง" };
  } finally {
    clearTimeout(ตัวจับเวลา);
  }
}
