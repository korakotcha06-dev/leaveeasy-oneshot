// คืนค่าเป็นข้อความ <svg> เอาไปต่อกับ HTML ได้เลย
function ไอคอน(ชื่อ, คลาสเพิ่ม) {
  var เส้น = เส้นไอคอน[ชื่อ];
  if (!เส้น) return "";
  return '<svg class="icon' + (คลาสเพิ่ม ? " " + คลาสเพิ่ม : "") + '" ' +
         'viewBox="0 0 24 24" aria-hidden="true" focusable="false">' + เส้น + "</svg>";
}

// เติมไอคอนให้ทุกจุดใน HTML ที่เขียน data-icon ไว้
(function เติมไอคอนในหน้า() {
  document.querySelectorAll("[data-icon]").forEach(function (ที่วาง) {
    ที่วาง.innerHTML = ไอคอน(ที่วาง.dataset.icon);
  });
})();

// ── ใส่ข้อความลงกล่องแจ้งเตือนพร้อมไอคอนที่ตรงกับชนิด ──
// ข้อความผ่าน textContent เสมอ ข้อมูลจากผู้ใช้จึงแทรกโค้ดเข้าหน้าเว็บไม่ได้
var ไอคอนของชนิด = {
  warn: "alert-triangle",
  error: "alert-circle",
  ok: "check"
};

function เตือนพร้อมไอคอน(กล่อง, ชนิด, ข้อความ) {
  กล่อง.innerHTML = ไอคอน(ไอคอนของชนิด[ชนิด] || "alert-circle");
  กล่อง.appendChild(document.createTextNode(ข้อความ));
  กล่อง.setAttribute("role", ชนิด === "ok" ? "status" : "alert");
}
