// บทบาทที่มีสิทธิ์พิจารณาใบลา ตามสเปกหัวข้อ 6 และ contract หัวข้อ 9
//
// บทบาทที่ว่างเปล่า (เกิดตอนที่ยังไม่มีไฟล์ users/{uid} ให้อ่าน) ถือว่า "ไม่ใช่ผู้พิจารณา"
// หลักคือ fail closed — ไม่รู้ว่าเป็นใคร ให้ถือว่าไม่มีสิทธิ์ไว้ก่อน ปลอดภัยกว่าเดาว่ามี
function เป็นผู้พิจารณา(ผู้ใช้) {
  const บทบาท = ผู้ใช้ && ผู้ใช้.role;
  return บทบาท === "manager" || บทบาท === "hr";
}

// เจ้าของใบลา เทียบด้วย uid ไม่ใช่ชื่อ เพราะชื่อซ้ำกันได้และเปลี่ยนได้ภายหลัง
function เป็นเจ้าของใบลา(ผู้ใช้, ใบ) {
  return Boolean(ผู้ใช้) && Boolean(ใบ) && ผู้ใช้.uid === ใบ.requesterId;
}

/**
 * แยกหน้าที่ (separation of duties) — คนยื่นใบลาไม่ใช่คนพิจารณาใบของตัวเอง
 *
 * ต่อให้ตำแหน่งเป็นหัวหน้างานหรือฝ่ายบุคคล ก็กดอนุมัติ/ไม่อนุมัติใบที่ตัวเองยื่นไม่ได้
 * เหตุผลไม่ใช่เรื่องเทคนิค แต่เป็นเรื่องการควบคุมภายใน ถ้าคนคนเดียวทั้งขอทั้งอนุมัติ
 * ขั้นตอนการอนุมัติก็ไม่เหลือความหมายอะไร และตรวจสอบย้อนหลังไม่ได้ว่าใครเป็นคนตัดสิน
 *
 * firestore.rules บังคับกฎเดียวกันนี้ที่ฝั่งเซิร์ฟเวอร์ด้วย (เทียบ requesterId กับ auth.uid)
 * ตรงนี้จึงเป็นแค่การบอกผู้ใช้ล่วงหน้า ไม่ใช่ด่านกันจริง
 */
function พิจารณาใบนี้ได้(ผู้ใช้, ใบ) {
  return เป็นผู้พิจารณา(ผู้ใช้) && !เป็นเจ้าของใบลา(ผู้ใช้, ใบ);
}

