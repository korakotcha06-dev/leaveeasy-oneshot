function วาดรายละเอียด() {
  if (!ใบลา) return;

  เติมข้อความ("detail-title", ใบลา.title);
  เติมข้อความ("detail-reason", ใบลา.reason);
  เติมข้อความ("detail-type", ใบลา.leaveTypeName);
  เติมข้อความ("detail-dates", formatDateRange(ใบลา.startDate, ใบลา.endDate));
  เติมข้อความ("detail-requester", ใบลา.requesterName);

  // ผู้อนุมัติอาจเป็นสตริงว่างได้ (contract หัวข้อ 1) ต้องขึ้นข้อความตามสเปกคำต่อคำ
  const ชื่อผู้อนุมัติ = (ใบลา.approverName || "").trim();
  เติมข้อความ("detail-approver", ชื่อผู้อนุมัติ || ไม่มีผู้อนุมัติ);

  // ป้ายสถานะเป็น HTML ก้อนเดียวจาก util.js ซึ่ง escape ข้อความสถานะมาให้แล้ว
  const ช่องสถานะ = document.getElementById("status-slot");
  if (ช่องสถานะ) ช่องสถานะ.innerHTML = statusBadgeHtml(ใบลา.status, "detail-status");

  // createdAt อาจเป็น null ชั่วคราวตอนเพิ่งเขียนด้วย serverTimestamp()
  // formatTimestamp จัดการกรณีนั้นให้แล้ว คืนสตริงว่างแทนที่จะพัง
  เติมข้อความ("detail-created", formatTimestamp(ใบลา.createdAt));
}

function วาดความเห็น() {
  const กล่อง = byTestId("approval-list");
  if (!กล่อง) return;

  if (รายการความเห็น.length === 0) {
    // สถานะว่างต้องมีข้อความบอก ไม่ใช่ปล่อยพื้นที่ว่างให้เดาว่าโหลดไม่ขึ้นหรือไม่มีข้อมูล
    กล่อง.innerHTML = '<div class="empty">ยังไม่มีความเห็นในใบลานี้</div>';
    return;
  }

  // ตรงนี้ต่อสตริงเป็น innerHTML จึงต้องผ่าน escapeHtml ทุกค่าที่มาจากผู้ใช้
  // ทั้งชื่อผู้เขียนและข้อความ — ชื่อก็เป็นข้อความที่คนกรอกเองตอนสมัครเหมือนกัน
  กล่อง.innerHTML = รายการความเห็น
    .map((ความเห็น) => {
      const ชื่อ = escapeHtml(ความเห็น.authorName || "ไม่ทราบชื่อผู้เขียน");
      const ข้อความ = escapeHtml(ความเห็น.message || "");
      const เวลา = escapeHtml(formatTimestamp(ความเห็น.createdAt));
      return (
        '<div class="card" data-testid="approval-item">' +
        '<div class="field-label">' +
        `<span data-testid="approval-author">${ชื่อ}</span>` +
        ` <span data-testid="approval-time">${เวลา}</span>` +
        "</div>" +
        `<div data-testid="approval-message">${ข้อความ}</div>` +
        "</div>"
      );
    })
    .join("");
}

/**
 * เปิด/ปิดปุ่มทั้งสาม ตามกฎเครื่องสถานะ
 *
 * กฎข้อ 1 (ปลายทางเปลี่ยนไม่ได้) และข้อ 2 (เฉพาะ manager/hr ที่ไม่ใช่เจ้าของใบ)
 * บังคับที่ปุ่มอนุมัติ/ไม่อนุมัติ
 * กฎข้อ 5 (ลบได้เฉพาะเจ้าของ และเฉพาะตอนรอพิจารณา) บังคับที่ปุ่มลบ
 *
 * ใช้ disabled ไม่ใช่การซ่อนปุ่ม เพราะผู้ใช้ควรเห็นว่ามีปุ่มนี้อยู่จริง
 * แต่ตอนนี้กดไม่ได้ ดีกว่าปุ่มหายไปเฉย ๆ แล้วผู้ใช้สงสัยว่าระบบพังหรือเปล่า
 */
function ปรับปุ่มการทำงาน() {
  const มีใบลา = Boolean(ใบลา);
  const ยังรอพิจารณา = มีใบลา && ใบลา.status === STATUS.PENDING;

  // เปลี่ยนสถานะได้ต้องครบ 3 อย่าง คือ ใบยังรอพิจารณา · เป็น manager หรือ hr
  // และ ไม่ใช่ใบของตัวเอง (แยกหน้าที่ · ดู พิจารณาใบนี้ได้() ด้านบน)
  const เปลี่ยนสถานะได้ = มีใบลา && ยังรอพิจารณา && พิจารณาใบนี้ได้(ผู้ใช้ปัจจุบัน, ใบลา);

  // ปุ่มลบใช้เงื่อนไขตรงข้ามกัน คือ "ต้องเป็นใบของตัวเอง" และยังรอพิจารณาอยู่
  const ลบได้ = มีใบลา && ยังรอพิจารณา && เป็นเจ้าของใบลา(ผู้ใช้ปัจจุบัน, ใบลา);

  const อ = ปุ่มอนุมัติ();
  const ม = ปุ่มไม่อนุมัติ();
  const ล = ปุ่มลบ();

  // กำลังทำงาน = มีคำสั่งเขียนฐานข้อมูลค้างอยู่ ปิดทุกปุ่มไว้ก่อนกันกดซ้ำ
  // การกดอนุมัติสองครั้งรัว ๆ ไม่ควรยิงคำสั่งเขียนสองรอบ
  if (อ) อ.disabled = กำลังทำงาน || !เปลี่ยนสถานะได้;
  if (ม) ม.disabled = กำลังทำงาน || !เปลี่ยนสถานะได้;
  if (ล) ล.disabled = กำลังทำงาน || !ลบได้;

  // ปุ่มที่กดไม่ได้ต้องมีคำอธิบายเสมอ ไม่ใช่เงียบ ๆ แล้วปล่อยให้ผู้ใช้เดาเอง
  // เคสนี้คือ manager หรือ hr เปิดใบลาที่ตัวเองเป็นคนยื่น ปุ่มพิจารณาจะถูกปิด
  // (ผู้ขอลาที่เป็น employee ไม่ต้องอธิบาย เพราะไม่เคยมีสิทธิ์พิจารณาอยู่แล้ว)
  const คำอธิบาย = document.getElementById("self-review-note");
  if (คำอธิบาย) {
    คำอธิบาย.hidden = !(
      ยังรอพิจารณา &&
      เป็นผู้พิจารณา(ผู้ใช้ปัจจุบัน) &&
      เป็นเจ้าของใบลา(ผู้ใช้ปัจจุบัน, ใบลา)
    );
  }
}

// ── โหลดข้อมูลใหม่จากฐานข้อมูล ───────────────────────────────

/**
 * อ่านใบลาและความเห็นใหม่ทั้งหมด แล้ววาดหน้าจอใหม่
 *
 * เรียกซ้ำทุกครั้งหลังเขียนข้อมูลสำเร็จ แทนที่จะแก้ตัวแปรในหน่วยความจำเอาเอง
 * เพราะความจริงอยู่ที่ฐานข้อมูล ไม่ใช่ที่หน้าจอ ถ้ามีคนอื่นแก้ใบเดียวกันอยู่
 * การอ่านใหม่จะเห็นของจริง ส่วนการเดาเองจะเห็นของปลอมที่ดูเหมือนถูก
 */
async function โหลดใหม่() {
  ใบลา = await getLeaveRequest(รหัสใบลา);

  if (!ใบลา) {
    showError(ช่องข้อความผิดพลาด, "ไม่พบใบลาที่ต้องการ อาจถูกลบไปแล้ว");
    รายการความเห็น = [];
    วาดความเห็น();
    ปรับปุ่มการทำงาน();
    return;
  }

  รายการความเห็น = await listApprovals(รหัสใบลา);
  วาดรายละเอียด();
  วาดความเห็น();
  ปรับปุ่มการทำงาน();
}

