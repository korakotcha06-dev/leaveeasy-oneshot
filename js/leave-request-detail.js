/**
 * เปลี่ยนสถานะใบลา — ทางเข้าทางเดียวของทั้งปุ่มอนุมัติและปุ่มไม่อนุมัติ
 *
 * ด่านตรวจทั้งหมดอยู่ที่นี่ ไม่ได้อยู่ที่ตัวปุ่ม เพราะ disabled เป็นแค่ของตกแต่ง
 * ใครแก้ HTML ในเบราว์เซอร์แล้วกดได้ ก็ยังต้องผ่านด่านเหล่านี้อยู่ดี
 * (และยังต้องผ่าน firestore.rules อีกชั้นที่ฝั่งเซิร์ฟเวอร์)
 */
async function เปลี่ยนสถานะ(สถานะใหม่) {
  if (กำลังทำงาน) return;
  clearError(ช่องข้อความผิดพลาด);

  if (!ใบลา) {
    showError(ช่องข้อความผิดพลาด, "ยังไม่ได้โหลดข้อมูลใบลา กรุณารีเฟรชหน้าอีกครั้ง");
    return;
  }

  // ── ด่านที่ 1 · กฎข้อ 1 สถานะปลายทางเปลี่ยนต่อไม่ได้ ──
  if (ใบลา.status !== STATUS.PENDING) {
    showError(
      ช่องข้อความผิดพลาด,
      `ใบลานี้มีสถานะ "${ใบลา.status}" ซึ่งเป็นสถานะสุดท้ายแล้ว เปลี่ยนสถานะต่อไม่ได้`
    );
    return;
  }

  // ── ด่านที่ 2 · กฎข้อ 2 เฉพาะหัวหน้างานกับฝ่ายบุคคล ──
  if (!เป็นผู้พิจารณา(ผู้ใช้ปัจจุบัน)) {
    showError(
      ช่องข้อความผิดพลาด,
      "เฉพาะหัวหน้างานและฝ่ายบุคคลเท่านั้นที่เปลี่ยนสถานะใบลาได้ ผู้ขอลาเปลี่ยนสถานะใบของตัวเองไม่ได้"
    );
    return;
  }

  // ── ด่านที่ 3 · แยกหน้าที่ ห้ามพิจารณาใบลาของตัวเอง ──
  //
  // ด่านนี้แยกจากด่านที่ 2 เพื่อให้ข้อความอธิบายคนละแบบ
  // "คุณไม่ใช่ผู้อนุมัติ" กับ "คุณเป็นผู้อนุมัติ แต่ใบนี้เป็นใบของคุณเอง"
  // เป็นคนละเรื่องกัน ผู้ใช้ต้องอ่านแล้วเข้าใจทันทีว่าติดเพราะอะไร
  if (เป็นเจ้าของใบลา(ผู้ใช้ปัจจุบัน, ใบลา)) {
    showError(
      ช่องข้อความผิดพลาด,
      "พิจารณาใบลาของตัวเองไม่ได้ ต้องให้หัวหน้างานหรือฝ่ายบุคคลคนอื่นเป็นผู้อนุมัติหรือไม่อนุมัติใบนี้"
    );
    return;
  }

  // ── ด่านที่ 4 · กฎข้อ 4 จะไม่อนุมัติได้ ต้องมีความเห็นก่อนอย่างน้อย 1 รายการ ──
  //
  // จงใจอ่านรายการความเห็นจากฐานข้อมูลใหม่ตรงนี้ ไม่ใช้ตัวแปรที่จำไว้ในหน้าจอ
  // เพราะตัวแปรในหน้าจอเป็นภาพถ่ายตอนโหลดหน้า ถ้าอีกคนเพิ่งลบ/เพิ่มความเห็นไป
  // ภาพนั้นจะเก่าแล้ว และเรากำลังตัดสินใจเรื่องสำคัญด้วยข้อมูลที่ไม่ใช่ของจริง
  if (สถานะใหม่ === STATUS.REJECTED) {
    รายการความเห็น = await listApprovals(รหัสใบลา);
    วาดความเห็น();
    if (รายการความเห็น.length === 0) {
      showError(
        ช่องข้อความผิดพลาด,
        "ต้องเขียนความเห็นอย่างน้อย 1 รายการก่อน จึงจะกดไม่อนุมัติได้ กรุณาพิมพ์เหตุผลในกล่องความเห็นด้านล่างแล้วกดส่งความเห็นก่อน"
      );
      return;
    }
  }

  กำลังทำงาน = true;
  ปรับปุ่มการทำงาน();
  try {
    // กฎข้อ 3 · updateLeaveStatus เขียนเฉพาะช่อง status ช่องเดียว (ดู js/data.js)
    // ห้ามเปลี่ยนไปใช้ setDoc หรือส่งทั้งก้อน ใบลาเดิมจะถูกเขียนทับหายทั้งใบ
    await updateLeaveStatus(รหัสใบลา, สถานะใหม่);
    กำลังทำงาน = false;
    await โหลดใหม่();
  } catch (err) {
    กำลังทำงาน = false;
    ปรับปุ่มการทำงาน();
    showError(ช่องข้อความผิดพลาด, describeError(err));
  }
}

/**
 * ลบใบลา — กฎข้อ 5
 * ลบได้เฉพาะเจ้าของใบ และเฉพาะตอนที่ยังเป็น "รอพิจารณา" และต้องยืนยันก่อนเสมอ
 */
async function ลบใบลา() {
  if (กำลังทำงาน) return;
  clearError(ช่องข้อความผิดพลาด);

  if (!ใบลา) {
    showError(ช่องข้อความผิดพลาด, "ยังไม่ได้โหลดข้อมูลใบลา กรุณารีเฟรชหน้าอีกครั้ง");
    return;
  }

  if (ใบลา.status !== STATUS.PENDING) {
    showError(
      ช่องข้อความผิดพลาด,
      `ลบได้เฉพาะใบลาที่สถานะยังเป็น "${STATUS.PENDING}" เท่านั้น ใบนี้มีสถานะ "${ใบลา.status}" แล้ว`
    );
    return;
  }

  if (!ผู้ใช้ปัจจุบัน || ผู้ใช้ปัจจุบัน.uid !== ใบลา.requesterId) {
    showError(ช่องข้อความผิดพลาด, "ลบได้เฉพาะใบลาที่ตัวเองเป็นผู้ยื่นเท่านั้น");
    return;
  }

  // ถามยืนยันก่อนเสมอ (สเปก US-07) เพราะการลบกู้คืนไม่ได้
  // ใช้ window.confirm ตรง ๆ เพราะโปรเจกต์นี้ห้ามใช้ไลบรารีภายนอก
  const ยืนยัน = window.confirm(
    `ยืนยันการลบใบลา "${ใบลา.title}" หรือไม่ การลบนี้ย้อนกลับไม่ได้`
  );
  if (!ยืนยัน) return;

  กำลังทำงาน = true;
  ปรับปุ่มการทำงาน();
  try {
    await deleteLeaveRequest(รหัสใบลา);
    // ลบสำเร็จแล้วต้องออกจากหน้านี้ทันที เพราะใบที่หน้านี้แสดงอยู่ไม่มีอยู่จริงแล้ว
    window.location.href = หน้ารายการ;
  } catch (err) {
    กำลังทำงาน = false;
    ปรับปุ่มการทำงาน();
    showError(ช่องข้อความผิดพลาด, describeError(err));
  }
}

/** ส่งความเห็นใหม่ลงโฟลเดอร์ย่อย approvals ของใบลานี้ */
async function ส่งความเห็น() {
  if (กำลังทำงาน) return;
  clearError(ช่องข้อความผิดพลาด);

  const ช่องพิมพ์ = byTestId("comment-input");
  const ปุ่มส่ง = byTestId("comment-submit");
  if (!ช่องพิมพ์) return;

  const ข้อความ = (ช่องพิมพ์.value || "").trim();

  // ข้อความว่างหรือมีแต่ช่องว่าง ต้องเตือนให้เห็น ไม่ใช่เงียบแล้วไม่ทำอะไร
  // ผู้ใช้ที่กดแล้วไม่มีอะไรเกิดขึ้นจะคิดว่าระบบพัง
  if (!ข้อความ) {
    showError(ช่องข้อความผิดพลาด, "กรุณาพิมพ์ความเห็นก่อนกดส่ง ส่งความเห็นว่างเปล่าไม่ได้");
    ช่องพิมพ์.focus();
    return;
  }

  if (!ใบลา) {
    showError(ช่องข้อความผิดพลาด, "ยังไม่ได้โหลดข้อมูลใบลา กรุณารีเฟรชหน้าอีกครั้ง");
    return;
  }

  if (ปุ่มส่ง) ปุ่มส่ง.disabled = true;
  try {
    // authorId ต้องเป็น uid ของคนที่ล็อกอินอยู่จริง กฎความปลอดภัยตรวจข้อนี้
    // authorName จดชื่อซ้ำไว้ เพื่อให้แสดงชื่อได้โดยไม่ต้องเปิดโฟลเดอร์ users อีกรอบ
    await addApproval(รหัสใบลา, {
      authorId: ผู้ใช้ปัจจุบัน.uid,
      authorName: ผู้ใช้ปัจจุบัน.name || ผู้ใช้ปัจจุบัน.email || "",
      message: ข้อความ
    });
    ช่องพิมพ์.value = "";
    รายการความเห็น = await listApprovals(รหัสใบลา);
    วาดความเห็น();
  } catch (err) {
    showError(ช่องข้อความผิดพลาด, describeError(err));
  } finally {
    if (ปุ่มส่ง) ปุ่มส่ง.disabled = false;
  }
}

// ── ผูกเหตุการณ์และเริ่มทำงาน ────────────────────────────────

function ผูกเหตุการณ์() {
  const อ = ปุ่มอนุมัติ();
  const ม = ปุ่มไม่อนุมัติ();
  const ล = ปุ่มลบ();
  const ฟอร์มความเห็น = document.getElementById("comment-form");

  if (อ) อ.addEventListener("click", () => เปลี่ยนสถานะ(STATUS.APPROVED));
  if (ม) ม.addEventListener("click", () => เปลี่ยนสถานะ(STATUS.REJECTED));
  if (ล) ล.addEventListener("click", () => ลบใบลา());

  if (ฟอร์มความเห็น) {
    ฟอร์มความเห็น.addEventListener("submit", (event) => {
      // กัน submit แบบเดิมของเบราว์เซอร์ที่จะรีโหลดทั้งหน้าและทำให้ข้อมูลที่โหลดไว้หายหมด
      event.preventDefault();
      ส่งความเห็น();
    });
  }
}

async function เริ่มทำงาน() {
  ผูกเหตุการณ์();

  // requireAuth คืน null พร้อมพาไปหน้า login เมื่อยังไม่ได้ล็อกอิน
  // ต้อง return ทันที อย่าทำงานต่อ เพราะหน้ากำลังจะเปลี่ยนไปที่อื่นแล้ว
  ผู้ใช้ปัจจุบัน = await requireAuth();
  if (!ผู้ใช้ปัจจุบัน) return;

  if (!รหัสใบลา) {
    showError(
      ช่องข้อความผิดพลาด,
      "ไม่พบรหัสใบลาใน URL กรุณาเปิดหน้านี้จากหน้ารายการใบลา"
    );
    return;
  }

  try {
    await โหลดใหม่();
  } catch (err) {
    // อ่านไม่ได้มักเป็น permission-denied เมื่อ employee เปิดใบของคนอื่น
    // describeError แปลรหัสของ Firebase เป็นภาษาไทยให้แล้ว
    showError(ช่องข้อความผิดพลาด, describeError(err));
  }
}

if (document.readyState === "loading") {
  document.addEventListener("DOMContentLoaded", เริ่มทำงาน);
} else {
  เริ่มทำงาน();
}
